/* design-system.js
   Renders the token sections of the design system page from assets/data/tokens.json
   (generated by `npm run tokens`), plus live chart examples built with lib.js. */

const GROUP_TITLES = {
  "color.surface": "Surfaces", "color.text": "Text", "color.border": "Borders", "color.accent": "Accent",
  "color.status": "Status", "color.chart": "Chart series", "color.emission": "Emission scale",
  "color.scene": "3D scene", "color.print": "PDF report",
};

function renderColors(tokens) {
  const box = $("colorGroups");
  const groups = new Map();
  for (const t of tokens.filter((x) => x.type === "color")) {
    const g = t.path.split(".").slice(0, 2).join(".");
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(t);
  }
  for (const [g, list] of groups) {
    box.append(h("h3", { class: "ds-sub" }, GROUP_TITLES[g] || g),
      h("div", { class: "ds-swatches" }, list.map((t) => h("div", { class: "swatch" },
        h("div", { class: "chip" }, h("i", { style: `background: var(${t.name})` })),
        h("div", { class: "meta" },
          h("code", {}, t.name),
          h("span", { class: "val" }, t.value),
          t.alias ? h("span", { class: "alias" }, `→ ${t.alias}`) : null,
          t.description ? h("span", { class: "desc" }, t.description) : null)))));
  }
}

function renderType(tokens) {
  const families = tokens.filter((t) => t.path.startsWith("font.family."));
  $("families").append(...families.map((t) => h("div", { class: "family-card frame" },
    h("code", {}, t.name),
    h("div", { class: "specimen big", style: `font-family: var(${t.name})` }, t.path.endsWith("code") ? "co2_released_t" : "Clinker 1,459,773 t"),
    h("div", { class: "alpha", style: `font-family: var(${t.name})` }, "ABCDEFGHIJKLMNOPQRSTUVWXYZ abcdefghijklmnopqrstuvwxyz 0123456789"),
    h("p", { class: "ds-usage" }, t.description))));

  $("typeScale").tBodies[0].append(...tokens.filter((t) => t.path.startsWith("font.size.")).map((t) => h("tr", {},
    h("td", {}, h("code", {}, t.name)), h("td", {}, t.value),
    h("td", {}, h("span", { class: "specimen", style: `font-size: var(${t.name})` }, t.description ? t.description.replace(/\.$/, "") : "Released CO2 139,996 t")))));

  const rows = tokens.filter((t) => t.path.startsWith("font.weight.") || t.path.startsWith("font.tracking."));
  $("weights").tBodies[0].append(...rows.map((t) => h("tr", {},
    h("td", {}, h("code", {}, t.name)), h("td", {}, t.value),
    h("td", {}, h("span", { class: "specimen", style: t.path.startsWith("font.weight.") ? `font-weight: var(${t.name}); font-size: var(--font-size-xl)` : `letter-spacing: var(${t.name}); font-size: var(--font-size-xl)` }, "Line 2 back within permit limit")))));
}

function renderTable(id, list) {
  $(id).tBodies[0].append(...list.map((t) => h("tr", {}, h("td", {}, h("code", {}, t.name)), h("td", {}, t.value), h("td", {}, t.description || ""))));
}

function renderAll(tokens) {
  $("allTokens").tBodies[0].append(...tokens.map((t) => h("tr", {},
    h("td", {}, h("code", {}, t.name)), h("td", {}, t.type),
    h("td", {}, t.alias ? `${t.value} (→ ${t.alias})` : t.value), h("td", {}, t.description || ""))));
}

function renderCharts() {
  const days = ["Mon 28", "Tue 29", "Wed 30", "Thu 1", "Fri 2", "Sat 3", "Sun 4", "Mon 5"];
  $("chartDemo").append(
    buildChart({ title: "Released CO2 by line, per day", kind: "bar", unit: "t", labels: days,
      series: [{ name: "Line 1", values: [2398, 2410, 2377, 2402, 2391, 2415, 2380, 1203] }, { name: "Line 2", values: [2305, 2311, 2296, 1540, 2318, 2302, 2120, 1166] }],
      reference_line: { value: 2688, label: "Daily equivalent of permit limit" } }),
    buildChart({ title: "Released intensity vs target", kind: "line", unit: "t CO2 per t clinker", labels: days,
      series: [{ name: "Line 1", values: [0.841, 0.846, 0.838, 0.842, 0.849, 0.844, 0.84, 0.843] }, { name: "Line 2", values: [0.862, 0.866, 0.859, null, 0.868, 0.861, 0.865, 0.863] }],
      reference_line: { value: 0.85, label: "Target 0.850" } }));
}

(async () => {
  renderCharts();
  try {
    const res = await fetch("../assets/data/tokens.json", { cache: "no-cache" });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const { tokens, count } = await res.json();
    renderColors(tokens);
    renderType(tokens);
    renderTable("shapeTokens", tokens.filter((t) => t.path.startsWith("shape.") || t.path.startsWith("effect.")));
    renderTable("sceneTokens", tokens.filter((t) => t.path.startsWith("scene.") || t.path.startsWith("motion.") || t.path.startsWith("layout.")));
    renderAll(tokens);
    $("tokenStatus").textContent = `${count} tokens, generated from tokens/tokens.json.`;
  } catch (e) {
    $("tokenStatus").className = "ds-note bad";
    $("tokenStatus").textContent = `Couldn't load the token list (${e.message}). If you opened this file directly, serve the folder instead: run \`npm run serve\` and open http://localhost:8080/design-system/. The components below still render.`;
  }
})();
